// Reads the approved internal catalogue (src/lib/pricing.ts, never modified) and produces:
//   1. src/lib/catalogue-public.ts  - the same names, inclusions and terms with every price removed (safe for the public site)
//   2. private/catalogue.json       - the full catalogue including prices, used only to build the private PDF (git-ignored)
// Run: node private/export-catalogue.mjs   (Node 22.18+ runs TypeScript directly)
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const c = await import(pathToFileURL(join(root, "src/lib/pricing.ts")).href);

const CURRENCY = /\bR\s?\d|\bZAR\b|\d{1,3}[ ,]\d{3}\b/;
const strip = ({ price, ...rest }) => rest;

const pub = {
  PACKAGES_PUBLIC: c.PACKAGES.map(strip),
  SPECIALIST_PUBLIC: c.SPECIALIST_SITES.map(strip),
  WEB_APPS_PUBLIC: c.WEB_APPS.map(strip),
  WEB_APP_SOLUTIONS: c.WEB_APP_SOLUTIONS,
  AI_SOLUTIONS_PUBLIC: c.AI_SOLUTIONS.map(strip),
  AI_AVAILABLE: c.AI_AVAILABLE,
  MAINTENANCE_PUBLIC: c.MAINTENANCE.map(strip),
  AI_MONTHLY_PUBLIC: c.AI_MONTHLY.map(strip),
  ADDONS_PUBLIC: c.ADDONS.map(strip),
  TERMS: c.TERMS,
  COMING_SOON: c.COMING_SOON,
};

const leak = JSON.stringify(pub).match(CURRENCY);
if (leak) throw new Error(`Public catalogue still contains a currency amount near: ${leak[0]}`);

const header = `/**
 * PUBLIC catalogue: approved names, inclusions and terms with all prices removed.
 * GENERATED by private/export-catalogue.mjs from src/lib/pricing.ts. Do not edit by hand and never import pricing.ts from site code.
 */
`;
const body = Object.entries(pub).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;`).join("\n\n");
writeFileSync(join(root, "src/lib/catalogue-public.ts"), `${header}\n${body}\n`);

writeFileSync(
  join(root, "private/catalogue.json"),
  JSON.stringify({ PACKAGES: c.PACKAGES, SPECIALIST_SITES: c.SPECIALIST_SITES, WEB_APPS: c.WEB_APPS, WEB_APP_SOLUTIONS: c.WEB_APP_SOLUTIONS, AI_SOLUTIONS: c.AI_SOLUTIONS, AI_AVAILABLE: c.AI_AVAILABLE, MAINTENANCE: c.MAINTENANCE, AI_MONTHLY: c.AI_MONTHLY, ADDONS: c.ADDONS, TERMS: c.TERMS }, null, 2),
);
console.log("Wrote src/lib/catalogue-public.ts and private/catalogue.json");
